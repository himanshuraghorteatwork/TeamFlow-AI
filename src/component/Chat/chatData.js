export function normalizeChats(chats) {
  return chats.map((chat) => ({
    ...chat,
    unreadCount: chat.unreadCount ?? 0,
    messages: (chat.messages ?? []).map((message) => ({
      ...message,
      id: message.id ?? `${chat.id}-${Math.random().toString(36).slice(2)}`,
      sender: message.sender ?? "Team member",
      text: message.text ?? "",
      time: message.time ?? "",
      own: message.own ?? false,
    })),
  }));
}